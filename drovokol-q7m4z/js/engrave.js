/* ---------- гравировка линиями: «ЛЕЗВИЕ» и стрелка к кромке под заточку (решение грилинга 2) ----------
   Шрифт — копия из editor/mangal/js/engrave.js (DIGITS, клетка 1×2, шаг 1,5 клетки, glyphSegs) + буквы Л, Е, З, В, И, знаки «>» и «-».
   Лазер проходит линии на малой мощности, слой ENGRAVE. Ручка при раскладке не зеркалится, поэтому надпись всегда читается сверху листа */
// цифра — клетка 1×2 (y вверх, как в DXF), между цифрами 0,5. «9» без нижней палочки — перевёрнутая она не похожа на «6»
const DIGITS={0:[[[0,0],[1,0],[1,2],[0,2],[0,0]]],1:[[[.5,0],[.5,2],[.2,1.7]],[[.2,0],[.8,0]]],2:[[[0,2],[1,2],[1,1],[0,1],[0,0],[1,0]]],3:[[[0,2],[1,2],[1,0],[0,0]],[[0,1],[1,1]]],
  4:[[[0,2],[0,1],[1,1]],[[1,2],[1,0]]],5:[[[1,2],[0,2],[0,1],[1,1],[1,0],[0,0]]],6:[[[1,2],[0,2],[0,0],[1,0],[1,1],[0,1]]],7:[[[0,2],[1,2],[1,0]]],
  8:[[[0,0],[1,0],[1,2],[0,2],[0,0]],[[0,1],[1,1]]],9:[[[1,1],[0,1],[0,2],[1,2],[1,0]]]};
// буквы дровокола: та же клетка 1×2, ломаные. «З» — со скосами в углах (как «з» у мангала), у «3» углы прямые: не спутать
const LETTERS={
  'Л':[[[0,0],[.3,2],[1,2],[1,0]]],
  'Е':[[[1,2],[0,2],[0,0],[1,0]],[[0,1],[.8,1]]],
  'З':[[[0,1.75],[.25,2],[.75,2],[1,1.75],[1,1.25],[.75,1],[.25,1]],[[.75,1],[1,.75],[1,.25],[.75,0],[.25,0],[0,.25]]],
  'В':[[[0,0],[0,2],[.75,2],[1,1.75],[1,1.25],[.75,1],[0,1]],[[.75,1],[1,.75],[1,.25],[.75,0],[0,0]]],
  'И':[[[0,2],[0,0],[1,2],[1,0]]],
  '>':[[[0,2],[1,1],[0,0]]],
  '-':[[[.15,1],[.85,1]]]};
const GLYPHS={...DIGITS,...LETTERS};
// отрезки строки t: клетка символа u × 2u мм, левый нижний угол (ox, oy), шаг 1,5 клетки. Неизвестный символ — ошибка, не пропуск
function glyphSegs(t,ox,oy,u){const seg=[];
  [...t].forEach((ch,i)=>{const G=GLYPHS[ch];if(!G)throw new Error(`гравировка: нет символа «${ch}»`);
    G.forEach(L=>{for(let k=0;k+1<L.length;k++)seg.push([ox+(i*1.5+L[k][0])*u,oy+L[k][1]*u,ox+(i*1.5+L[k+1][0])*u,oy+L[k+1][1]*u]);});});
  return seg;}
// «ЛЕЗВИЕ» и стрелка к кромке под заточку — в координатах ручки h (ось в (0, 0), участок с лезвием вдоль +X, кромка лезвия h.bladeEdge — со стороны +Y).
// Надпись высотой BLADE_TXT посередине участка с лезвием, ниже оси ручки; справа от неё стрелка вверх, остриё за BLADE_GAP до кромки
const BLADE_WORD='ЛЕЗВИЕ',BLADE_TXT=8,BLADE_GAP=5;
function bladeMark(h){const [a,b]=h.bladeEdge,ey=a[1],u=BLADE_TXT/2,w=(BLADE_WORD.length*1.5-.5)*u,ar=4,
    cx=(a[0]+b[0])/2,y0=-ey/2-u,x0=cx-(w+2*ar+3)/2,
    seg=glyphSegs(BLADE_WORD,x0,y0,u),ax=x0+w+3+ar,top=ey-BLADE_GAP;
  seg.push([ax,y0,ax,top],[ax-ar,top-ar,ax,top],[ax+ar,top-ar,ax,top]);   // стрелка: древко от низа надписи к кромке, остриё
  return seg;}
