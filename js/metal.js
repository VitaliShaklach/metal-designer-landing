// Справочник металла.
// Масса 1 м профильной трубы — по формуле ГОСТ 8639-82 (квадратная) и ГОСТ 8645-68 (прямоугольная):
//   m = 0,0157 · t · (A + B − 2,86 · t), кг/м, где A, B — стороны, t — стенка, всё в мм.
// Масса 1 м круглой трубы — по ГОСТ 10704-91: m = 0,02466 · t · (D − t), кг/м.
// Масса 1 м² листа — по ГОСТ 19903-2015 при плотности стали 7850 кг/м³: 7,85 кг на каждый мм толщины.
// Квадрат, полоса и пруток — по площади сечения, уголок — по сортаменту ГОСТ 8509-93.
(function (MD) {
  function tube(a, b, t) {
    const kgPerM = Math.round(0.0157 * t * (a + b - 2.86 * t) * 100) / 100;
    return { name: `${a}×${b}×${t}`, kgPerM };
  }

  function pipe(d, t) {
    const kgPerM = Math.round(0.02466 * t * (d - t) * 100) / 100;
    return { name: `Ø${d}×${t}`, kgPerM };
  }

  const sheetKgPerM2 = t => 7.85 * t;

  // Сплошной прокат — по площади сечения в мм² при 7850 кг/м³: квадрат, полоса, круглый пруток.
  const solid = (name, mm2) => ({ name, kgPerM: Math.round(mm2 * 7.85e-3 * 1000) / 1000 });
  const square = a => solid(`Квадрат ${a}×${a}`, a * a);
  const strip = (b, t) => solid(`Полоса ${b}×${t}`, b * t);
  const rod = d => solid(`Пруток Ø${d}`, Math.PI * d * d / 4);

  // Уголок равнополочный — масса из сортамента ГОСТ 8509-93: у него скруглены углы, по формуле не посчитать точно.
  const ANGLE_KG = { '30×3': 1.36, '30×4': 1.78, '40×4': 2.42, '50×5': 3.77 };
  const angle = (a, t) => ({ name: `Уголок ${a}×${a}×${t}`, kgPerM: ANGLE_KG[`${a}×${t}`] });

  MD.metal = { tube, pipe, sheetKgPerM2, square, strip, rod, angle };
})(window.MD = window.MD || {});
